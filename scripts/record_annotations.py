ROOT = Path(__file__).resolve().parents[1]
DECISIONS = {}


def record(label, ids, reason):
    for number in ids.split():
        key = f"C{int(number):04d}"
        if key in DECISIONS:
            raise ValueError(f"Duplicate decision: {key}")
        DECISIONS[key] = {"candidate_id": key, "label": label, "reason": reason}


